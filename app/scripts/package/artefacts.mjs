/**
 * Inno Setup's AppId per flavour: what Windows files the install under in Apps & features, and how a
 * newer installer recognises the older install it upgrades. PERMANENT: changing one makes the next
 * version install beside the old one instead of over it. Generated once on 2026-09-23.
 */
export const INSTALLER_APP_IDS = {internal: "A8670C1C-E426-458C-A43C-79AA5B652C60", release: "C2EDC4C4-FB80-4F50-A645-04DCA45A2DD1"};

/**
 * Windows.Graphics.Capture, which the reader captures with, arrived in Windows 10 version 1903
 * (build 18362): the installer refuses anything older rather than install an app that cannot read.
 */
export const WINDOWS_MIN_VERSION = "10.0.18362";

/** A value for an Inno Setup script line: quotes doubled, and no line break or control character at all. */
export function innoValue(value) {
  const text = String(value);
  if (/[\x00-\x1f]/.test(text)) throw new Error("INNO_VALUE_CONTROL_CHARACTER");
  return text.split('"').join('""');
}

/**
 * The whole Inno Setup script for one Windows app folder. Pure, so what the tests read is what ISCC
 * compiles. The install is per user (`PrivilegesRequired=lowest`: no administrator prompt, installed
 * under %LOCALAPPDATA%\Programs), its Start menu shortcut carries the app's AppUserModelID (without
 * it Windows shows none of the app's notifications), a running copy is closed before files are
 * replaced, and the previous version's resources are removed first so no stale file survives an
 * upgrade. Uninstalling removes the app and leaves the user's data, as on macOS.
 */
export function innoScript({flavour, appName, version, fileVersion, publisher, appUserModelId, sourceDir, iconPath, outputDir, outputBaseName}) {
  const appId = Object.hasOwn(INSTALLER_APP_IDS, flavour) ? INSTALLER_APP_IDS[flavour] : null;
  if (appId === null) throw new Error("INSTALLER_FLAVOUR_UNKNOWN");
  const v = innoValue;
  const exe = `${appName}.exe`;
  return [
    "; Generated by app/scripts/package/artefacts.mjs (innoScript). Do not edit: change the generator.",
    "[Setup]",
    // Inno's `{{` is a literal brace: the AppId is written as {GUID}.
    `AppId={{${appId}}`,
    `AppName=${v(appName)}`,
    `AppVersion=${v(version)}`,
    `AppVerName=${v(appName)} ${v(version)}`,
    `AppPublisher=${v(publisher)}`,
    `VersionInfoVersion=${v(fileVersion)}`,
    `VersionInfoProductName=${v(appName)}`,
    `DefaultDirName={autopf}\\${v(appName)}`,
    "DisableDirPage=auto",
    "DisableProgramGroupPage=yes",
    "PrivilegesRequired=lowest",
    "ArchitecturesAllowed=x64compatible",
    "ArchitecturesInstallIn64BitMode=x64compatible",
    `MinVersion=${WINDOWS_MIN_VERSION}`,
    `SetupIconFile=${v(iconPath)}`,
    `UninstallDisplayIcon={app}\\${v(exe)}`,
    `UninstallDisplayName=${v(appName)}`,
    "CloseApplications=yes",
    "RestartApplications=no",
    "Compression=lzma2/max",
    "SolidCompression=yes",
    "WizardStyle=modern",
    `OutputDir=${v(outputDir)}`,
    `OutputBaseFilename=${v(outputBaseName)}`,
    "",
    "[Languages]",
    'Name: "english"; MessagesFile: "compiler:Default.isl"',
    "",
    "[InstallDelete]",
    'Type: filesandordirs; Name: "{app}\\resources"',
    'Type: filesandordirs; Name: "{app}\\locales"',
    "",
    "[Files]",
    `Source: "${v(sourceDir)}\\*"; DestDir: "{app}"; Flags: ignoreversion recursesubdirs createallsubdirs`,
    "",
    "[Icons]",
    `Name: "{autoprograms}\\${v(appName)}"; Filename: "{app}\\${v(exe)}"; AppUserModelID: "${v(appUserModelId)}"`,
    "",
    "[Run]",
    `Filename: "{app}\\${v(exe)}"; Description: "Open ${v(appName)}"; Flags: nowait postinstall skipifsilent`,
    ""
  ].join("\r\n");
}

/**
 * What a Windows artefacts run may be made from. The bundle must have been through the fuse step; a
 * release must also be signed, which on Windows is not set up yet (owner decision, 2026-09-23: unsigned
 * for now), so today only an internal build gets artefacts.
 */
export function windowsArtefactDecision({flavour, report}) {
  if (flavour !== "internal" && flavour !== "release") return {error: "BAD_FLAVOUR"};
  if (!report || report.platform !== "win32") return {error: "BUNDLE_NOT_WINDOWS"};
  if (report.fused !== true) return {error: "ARTEFACT_NEEDS_FUSED"};
  if (flavour === "release" && report.signed !== true) return {error: "ARTEFACT_NEEDS_SIGNED"};
  return {ok: true};
}

/** The ZIP of the app folder, by Windows' own bsdtar (`tar -a` picks the format from `.zip`). */
export function winZipCommand({bundleDir, folderName, zipPath}) {
  return ["tar.exe", ["-a", "-c", "-f", zipPath, "-C", bundleDir, folderName]];
}

/** `--notarize <profile>` from argv; the `=` spelling and repeats refuse; the value is a keychain profile NAME. */
export function parseNotarizeArg(argv) {
  const spellings = argv.filter((a) => typeof a === "string" && a.startsWith("--notarize"));
  if (spellings.length === 0) return {profile: null};
  if (spellings.length > 1 || spellings[0] !== "--notarize") return {error: "BAD_NOTARIZE"};
  const value = argv[argv.indexOf("--notarize") + 1];
  if (typeof value !== "string" || !value.trim() || value.startsWith("-")) return {error: "BAD_NOTARIZE"};
  return {profile: value.trim()};
}

/**
 * Whether this run notarises, and why not. Only a bundle signed under a Developer ID can be
 * notarised; a release build must be; an internal build may skip it.
 */
export function notarizeDecision({flavour, report, profile}) {
  if (flavour !== "internal" && flavour !== "release") return {error: "BAD_FLAVOUR"};
  if (!report || report.signed !== true) return {error: "ARTEFACT_NEEDS_SIGNED"};
  if (profile === null || profile === undefined) return flavour === "release" ? {error: "NOTARIZE_REQUIRED"} : {skip: true};
  if (report.developerId !== true) return {error: "NOTARIZE_NEEDS_DEVELOPER_ID"};
  return {profile};
}

