/**
 * `Clave-Agent-Internal-0.1.0-20260922.0815-arm64`: the app name without spaces, the version, the build
 * number, the architecture (`x64` for the Windows build).
 */
export function artefactBaseName(info, arch = "arm64") {
  if (!info || typeof info.appName !== "string" || !info.appName.trim() || typeof info.version !== "string" || typeof info.buildNumber !== "string") return null;
  const name = info.appName.trim().split(/\s+/).join("-").replace(/[^A-Za-z0-9.-]/g, "");
  if (!name) return null;
  return `${name}-${info.version}-${info.buildNumber}-${arch}`;
}

